    float Ay = (float)i2c_read(Acc_Y,1)/4096.0; //(4096 là d? nh?y tuong ?ng: coi datasheet)
    float Az = (float)i2c_read(Acc_Z,1)/4096.0; //(4096 là d? nh?y tuong ?ng: coi datasheet)

    // Tinh toan roll, pitch
    roll = atan2(Ay,sqrt(pow(Ax,2)+pow(Az,2)))*180/3.14;
    pitch = atan2(Ax,sqrt(pow(Ay,2)+pow(Az,2)))*180/3.14; // hàm pow là hàm mu; M_PI là pi (t?t c? trong thu vi?n math.h)
