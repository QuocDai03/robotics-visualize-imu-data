void i2c_write(uint8_t reg, uint8_t value)
{
	uint8_t data[2];
	data[0] = reg;
	data[1] = value;
	HAL_I2C_Master_Transmit(&hi2c1, mpu_address,data,2,10);
}

int16_t i2c_read(uint8_t reg, uint8_t byte_read)
{
	uint8_t high,low;
	int16_t data;
	HAL_I2C_Mem_Read(&hi2c1,mpu_address,reg,1,&high,byte_read,100);
	HAL_I2C_Mem_Read(&hi2c1,mpu_address,reg+1,1,&low,byte_read,100);
	data = (int16_t) (high<<8) | low;
	return data;
}

void Init_6050 (void)
{
	//sample_rate 500Hz
	i2c_write(Sample_rate,15);
	// Không s? d?ng ngu?n xung ngoài, t?t DLFP
	i2c_write(Config,0);
	//gyro FS: +- 500 o/s
	i2c_write(Gyro_config,0x08);
	// acc FS: +-8g
	i2c_write(Acc_config,0x10);
	//turn on Interrupt c?a data ready
	i2c_write(Interrupt,1);
	//choose pulse source Gyro X
	i2c_write(PWR_Management,0x01);
}

void send_char(char data)
{
	while((USART1->SR&(1<<6))==0);
	USART1->DR = data;
}
void send_string(char *str)
{
	while (*str) send_char(*str++);
}
